function renderCardMarkup(html, small = true) {
  return html.replace(/\[\[([^\]]+)\]\]/g, (_, s) =>
    '<span class="cards-inline">' + parseCards(s).map(c => cardHTML(c, small ? 'sm' : '')).join('') + '</span>');
}

